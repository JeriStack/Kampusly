/**
 * Tiny text generator: swaps letters, digits and a few symbols for their Unicode superscript
 * look-alikes, e.g. "Hello 123" becomes "ᴴᵉˡˡᵒ ¹²³". Characters without a superscript form
 * (spaces, most punctuation, emoji, other scripts) are left as they are.
 */
const TINY_CHARACTERS: Record<string, string> = {
  a: 'ᵃ', b: 'ᵇ', c: 'ᶜ', d: 'ᵈ', e: 'ᵉ', f: 'ᶠ', g: 'ᵍ', h: 'ʰ', i: 'ⁱ', j: 'ʲ',
  k: 'ᵏ', l: 'ˡ', m: 'ᵐ', n: 'ⁿ', o: 'ᵒ', p: 'ᵖ', q: 'ᵠ', r: 'ʳ', s: 'ˢ', t: 'ᵗ',
  u: 'ᵘ', v: 'ᵛ', w: 'ʷ', x: 'ˣ', y: 'ʸ', z: 'ᶻ',
  0: '⁰', 1: '¹', 2: '²', 3: '³', 4: '⁴', 5: '⁵', 6: '⁶', 7: '⁷', 8: '⁸', 9: '⁹',
  '+': '⁺', '-': '⁻', '=': '⁼', '(': '⁽', ')': '⁾',
}

/** Unicode has capital superscripts for only some letters; the rest fall back to lowercase. */
const TINY_CAPITALS: Record<string, string> = {
  A: 'ᴬ', B: 'ᴮ', D: 'ᴰ', E: 'ᴱ', G: 'ᴳ', H: 'ᴴ', I: 'ᴵ', J: 'ᴶ', K: 'ᴷ', L: 'ᴸ',
  M: 'ᴹ', N: 'ᴺ', O: 'ᴼ', P: 'ᴾ', R: 'ᴿ', T: 'ᵀ', U: 'ᵁ', V: 'ⱽ', W: 'ᵂ',
}

export function toTinyText(text: string): string {
  // Array.from keeps surrogate pairs (emoji) intact.
  return Array.from(
    text,
    (character) =>
      TINY_CAPITALS[character] ?? TINY_CHARACTERS[character.toLowerCase()] ?? character,
  ).join('')
}
